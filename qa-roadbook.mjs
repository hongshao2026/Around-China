/** Optional browser check: install playwright and @axe-core/playwright, then run node qa-roadbook.mjs. */
import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const moduleRoot=process.env.ROADBOOK_QA_MODULES;
const {chromium}=await import(moduleRoot?pathToFileURL(resolve(moduleRoot,'playwright/index.mjs')).href:'playwright');
const {default:AxeBuilder}=await import(moduleRoot?pathToFileURL(resolve(moduleRoot,'@axe-core/playwright/dist/index.mjs')).href:'@axe-core/playwright');
const target=process.env.ROADBOOK_URL||'http://127.0.0.1:4174/';
const output=process.env.ROADBOOK_QA_OUTPUT||'qa-output';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
try {
 const context=await browser.newContext({viewport:{width:1440,height:1100},locale:'zh-CN',reducedMotion:'reduce',acceptDownloads:true});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 await page.goto(target,{waitUntil:'networkidle'});
 assert.ok(await page.locator('#roadbook-view').isVisible());
 assert.equal(await page.locator('[data-roadbook-row]').count(),147);
 assert.match(await page.title(),/完整路书/);
 assert.equal(await page.locator('[data-roadbook-row] time').first().innerText(),'2026-10-01');
 assert.match(await page.locator('[data-roadbook-row]').last().innerText(),/东兴/);
 await page.screenshot({path:resolve(output,'roadbook-desktop.png'),fullPage:true});
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 await writeFile(resolve(output,'roadbook-a11y.json'),JSON.stringify(axe.violations,null,2));
 assert.deepEqual(axe.violations.map(v=>({id:v.id,help:v.help,nodes:v.nodes.length})),[]);
 // CSV always exports all plan rows, even while the table is filtered.
 await page.locator('#roadbook-search').fill('密山');
 assert.ok(await page.locator('[data-roadbook-row]').count()<147);
 const downloadEvent=page.waitForEvent('download');
 await page.locator('[data-download-plan]').click();
 const download=await downloadEvent;
 const csvPath=resolve(output,'complete-roadbook.csv');await download.saveAs(csvPath);
 const csv=await readFile(csvPath,'utf8');
 assert.equal(csv.trim().split('\r\n').length,148);
 assert.match(csv,/上午安排/);assert.match(csv,/下午安排/);assert.match(csv,/住宿估算元每晚/);assert.match(csv,/东兴/);
 await page.locator('[data-table-day]').first().click();
 assert.ok(await page.locator('#route-view').isVisible());
 assert.match(await page.locator('#day-detail').innerText(),/密山/);
 assert.ok(await page.locator('.leaflet-container').isVisible());
 await page.getByRole('button',{name:'拆成两天开',exact:true}).click();
 await page.getByRole('button',{name:'这里多住1晚',exact:true}).click();
 await page.locator('[data-return-roadbook]').click();
 assert.ok(await page.locator('#roadbook-view').isVisible());
 await page.locator('#roadbook-view [data-clear-filters]').first().click();
 assert.equal(await page.locator('[data-roadbook-row]').count(),149);
 assert.equal(await page.locator('.roadbook-kind').filter({hasText:'新增休整'}).count(),1);
 await page.locator('#departure').fill('2026-10-12');await page.locator('#roadbook-search').focus();
 assert.equal(await page.locator('[data-roadbook-row] time').first().innerText(),'2026-10-12');
 await page.getByRole('button',{name:'旅行预算',exact:true}).click();
 await page.locator('#budget-hotel').fill('300');await page.locator('#budget-food').focus();
 await page.getByRole('button',{name:'完整路书',exact:true}).click();
 assert.equal(await page.locator('.roadbook-price').first().innerText(),'¥225—¥405 / 晚');
 await page.getByRole('button',{name:'绕行备选',exact:true}).click();
 await page.locator('input[name=highland][value=inland]').check();
 await page.getByRole('button',{name:'完整路书',exact:true}).click();
 assert.equal(await page.locator('[data-roadbook-row]').count(),140);
 await page.locator('#roadbook-stage').selectOption('inland');
 assert.ok(await page.locator('[data-roadbook-row]').count()>0);
 assert.equal(await page.locator('#stage-filter').inputValue(),'inland');
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('#roadbook-stage').inputValue(),'inland');
 assert.ok(await page.locator('#roadbook-view').isVisible());
 await page.locator('#roadbook-search').fill('不存在的目的地abc');
 assert.ok(await page.locator('#roadbook-body').getByText('没有找到对应目的地。').isVisible());
 assert.ok(await page.locator('#print-roadbook').isDisabled());
 await page.locator('#roadbook-clear').click();
 assert.equal(await page.evaluate(()=>document.activeElement.id),'roadbook-search');
 assert.ok(await page.locator('[data-roadbook-row]').count()>0);
 await page.locator('#roadbook-stage').focus();await page.keyboard.press('Alt+ArrowDown');await page.keyboard.press('Escape');
 await page.locator('#roadbook-view [data-clear-filters]').first().click();
 // Frozen identifiers, keyboard horizontal scroll and mobile page reflow.
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 const frame=page.locator('#roadbook-scroll');
 assert.ok(await frame.evaluate(el=>el.scrollWidth>el.clientWidth));
 await frame.focus();await page.keyboard.press('ArrowRight');
 await page.waitForFunction(()=>document.querySelector('#roadbook-scroll').scrollLeft>0);
 await frame.evaluate(el=>{el.scrollLeft=500;el.scrollTop=350;});
 await page.screenshot({path:resolve(output,'roadbook-mobile.png'),fullPage:true});
 assert.ok(await page.getByRole('button',{name:'出发准备',exact:true}).isVisible());
 await page.getByRole('button',{name:'出发准备',exact:true}).click();
 assert.ok(await page.locator('#prepare-view').isVisible());
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 // Fresh full plan in print: actual PDF rendering, including the last itinerary day.
 const printPage=await context.newPage();
 await printPage.goto(target,{waitUntil:'networkidle'});
 await printPage.evaluate(()=>localStorage.removeItem('border-roadbook-v1'));
 await printPage.goto(target,{waitUntil:'networkidle'});
 await printPage.emulateMedia({media:'print'});
 assert.equal(await printPage.locator('#roadbook-scroll').evaluate(el=>getComputedStyle(el).overflow),'visible');
 await printPage.pdf({path:resolve(output,'roadbook-print.pdf'),preferCSSPageSize:true,printBackground:true});
 // A missing map tile must not prevent reading the complete text table.
 const offline=await context.newPage();await offline.route('https://tile.openstreetmap.org/**',r=>r.abort());
 await offline.goto(target,{waitUntil:'networkidle'});
 assert.equal(await offline.locator('[data-roadbook-row]').count(),147);
 assert.match(await offline.locator('[data-roadbook-row]').last().innerText(),/东兴/);
 assert.deepEqual(errors,[]);
 console.log('PASS complete 147-day table; 149 days after split/rest; 140 with inland detour; dates/lodging; shared filters; reload; full CSV; no-results; keyboard; 390px mobile; PDF generation; tile failure; axe (0 violations); no JS errors.');
} finally {await browser.close();}
